// ============================================
// Repair 백엔드 서버 - 메인 진입점
// ============================================
// 이 파일은 서버 애플리케이션의 시작점입니다.
// 서버 초기화, 데이터베이스 연결, 백그라운드 서비스 시작 등을 담당합니다.
// ============================================

package main

import (
	"fmt"
	"os"
	"repair/global/config" // 서버 설정 (버전, 모드, 경로 등)
	"repair/global/log"    // 로깅 시스템
	"repair/models"        // 데이터 모델 및 DB 초기화
	"repair/services"      // 백그라운드 서비스 (HTTP, Cron, 알림 등)
	"runtime"

	"math/rand"
	"time"
)

// ============================================
// init: 프로그램 시작 전 초기화
// ============================================
// main() 함수보다 먼저 자동으로 실행됩니다.
func init() {
	// CPU 코어 수만큼 병렬 처리 활성화
	// 예: 8코어 CPU라면 8개의 고루틴을 동시에 실행 가능
	runtime.GOMAXPROCS(runtime.NumCPU())

	// 난수 생성기 초기화 (현재 시간을 시드로 사용)
	// 매번 다른 난수를 생성하기 위해 필요
	rand.New(rand.NewSource(time.Now().UnixNano()))
}

// ============================================
// main: 서버 메인 함수
// ============================================
func main() {
	// ============================================
	// 1. 로깅 시스템 초기화
	// ============================================
	log.Init()
	log.Info().Str("Version", config.Version).Str("Mode", config.Mode).Msg("Start")
	// 서버 시작 로그: 버전과 모드(development/production) 출력

	// ============================================
	// 2. 캐시 초기화
	// ============================================
	// 데이터베이스 연결 풀, 메모리 캐시 등을 초기화합니다.
	models.InitCache()

	// ============================================
	// 3. 파일 업로드 디렉토리 생성
	// ============================================
	// 상세 파일을 저장할 디렉토리를 생성합니다.
	// 이미 존재하면 무시되며, 권한은 0755 (rwxr-xr-x)로 설정됩니다.
	os.MkdirAll(fmt.Sprintf("%v/detail", config.UploadPath), 0755)

	// ============================================
	// 4. 백그라운드 서비스 시작
	// ============================================
	// go 키워드로 별도 고루틴(경량 스레드)에서 실행됩니다.

	// Cron: 정기적인 작업 스케줄러 (예: 매일 자정에 데이터 정리)
	go services.Cron()

	// FCM: Firebase Cloud Messaging (푸시 알림) - 현재 비활성화
	//go services.Fcm()

	// Notify: 실시간 알림 서비스 (WebSocket 또는 Socket.IO)
	go services.Notify()

	// ============================================
	// 5. HTTP 서버 시작 (메인 스레드 블로킹)
	// ============================================
	// HTTP 서버를 시작하고 요청 대기 상태로 들어갑니다.
	// 이 함수는 서버가 종료될 때까지 리턴하지 않습니다.
	services.Http()
}
